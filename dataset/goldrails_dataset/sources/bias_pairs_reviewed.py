"""B2 counterfactual pairs that passed review, as scorable F7 rows: human review in v1.1, single-AI reference review
(label_basis llm, review_status ai_reviewed) in the provisional v1.1-ai.

The candidates (``dataset/frozen/review-packets/_lead/bias/*.candidates.jsonl``) are generated by
``goldrails_dataset.bias_pairs`` with no labels on the counterfactual side. ``goldrails_dataset.reviews`` compiles the
reviewers' B2 sheets into ``dataset/frozen/reviews.jsonl``: a pair is kept only when two reviewers (or an adjudicator)
agree that meaning, fluency and register survived the edit and that both texts need the same action. This loader emits
both texts of every kept pair with that action as ``expected`` and label basis ``human``; everything else stays out.
The build then marks them ``reviewed`` because their (id, label) is in the review file.

Ids on the examined list (``dataset/frozen/examined-ids.txt``) are forced to the tuning split by the build, whatever
their review; only pairs from a packet nobody read before review can be test rows.
"""
from __future__ import annotations

import dataclasses
import json
from pathlib import Path

from ..records import Record

NAME = "bias_pairs_reviewed"
FROZEN = Path(__file__).resolve().parents[2] / "frozen"
CANDIDATES = FROZEN / "review-packets" / "_lead" / "bias"
REVIEWS = FROZEN / "reviews.jsonl"


def kept_labels() -> dict:
    if not REVIEWS.exists():
        return {}
    out = {}
    for line in REVIEWS.read_text(encoding="utf-8").splitlines():
        if line.strip():
            d = json.loads(line)
            if d.get("packet") == "b2" and d.get("final") is True and d.get("label") in ("yes", "no"):
                out[d["id"]] = d["label"]
    return out


def ai_kept_labels(ai_reference) -> dict:
    """Record id -> label for pairs a single AI reviewer kept (mapped-ai-reference.jsonl, eligible rows)."""
    out = {}
    for line in (Path(ai_reference) / "mapped-ai-reference.jsonl").read_text(encoding="utf-8").splitlines():
        d = json.loads(line)
        if d["packet"].startswith("b2") and d.get("eligible_for_ai_reference") and d.get("label") in ("yes", "no"):
            out[d["id"]] = d["label"]
    return out


def load(limit=None, ai_reference=None) -> list:
    """Kept pairs. With ``ai_reference`` (a provisional build), labels come from the single AI review instead of the
    human review file; those rows keep label basis llm and review status ai_reviewed."""
    kept = ai_kept_labels(ai_reference) if ai_reference else kept_labels()
    basis, status = ("llm", "ai_reviewed") if ai_reference else ("human", None)
    out = []
    for f in sorted(CANDIDATES.glob("*.candidates.jsonl")) if CANDIDATES.exists() else []:
        for line in f.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            r = Record.from_dict(json.loads(line))
            if r.id not in kept:
                continue
            prov = dataclasses.replace(r.provenance, source=NAME, exclude_reason=None, label_basis=basis)
            out.append(dataclasses.replace(r, expected=kept[r.id], provenance=prov, review_status=status))
    return out[:limit] if limit else out
